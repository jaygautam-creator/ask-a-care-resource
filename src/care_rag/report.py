"""Build results/RESULTS.md from the saved runs in results/*/ (tables + worst-answer shortlist)."""

from __future__ import annotations

import json

from care_rag.config import RESULTS_DIR

RETRIEVAL_RUNS = [
    ("bm25", "BM25 only"),
    ("dense", "Dense only (multilingual-e5-base)"),
    ("hybrid", "Hybrid (dense + BM25, RRF)"),
    ("hybrid_small_chunks", "Hybrid, 150-word chunks"),
    ("hybrid_rerank", "Hybrid + bge-reranker-v2-m3 (568M)"),
    ("hybrid_rerank_small", "Hybrid + mMiniLM reranker (118M) - default"),
    ("hybrid_rerank_small_rewrite", "Hybrid + mMiniLM reranker + LLM query rewrite"),
]
ANSWER_RUNS = [
    ("hybrid", "Hybrid, no reranker"),
    ("hybrid_rerank_small", "Hybrid + reranker (default)"),
    ("hybrid_rerank_small_rewrite", "Hybrid + reranker + query rewrite"),
]


def _load(name: str):
    p = RESULTS_DIR / name / "summary.json"
    return json.loads(p.read_text()) if p.exists() else None


def _rows(name: str) -> list[dict]:
    p = RESULTS_DIR / name / "per_question.jsonl"
    return [json.loads(line) for line in open(p, encoding="utf-8")] if p.exists() else []


def _f(x, pct=False) -> str:
    if x is None:
        return "-"
    return f"{100 * x:.0f}%" if pct else f"{x:.2f}"


def _ms(x) -> str:
    if x is None:
        return "-"
    return f"{x:.0f} ms" if x < 1000 else f"{x / 1000:.1f} s"


def badness(r: dict) -> float:
    """Higher = worse. Wrong refusal decisions first, then unfaithful / incomplete answers."""
    if not r["answerable"]:
        return 3.0 if not r["refused"] else 0.0
    if r["refused"]:
        return 2.5
    score = 0.0
    if r.get("faithfulness") is not None:
        score += 1.5 * (1 - r["faithfulness"])
    if r.get("key_fact_recall") is not None:
        score += 1 - r["key_fact_recall"]
    score += 0.5 * (1 - r.get("hit@5", 1))
    score += 0.5 * bool(r.get("unverified_numbers"))
    return score


def write_report() -> str:
    out = ["# Results\n", "_Generated by `python -m care_rag.cli report` from `results/*/`._\n"]

    out.append("## Retrieval (answerable questions, document level)\n")
    out.append("| Config | hit@1 | hit@3 | hit@5 | recall@5 | MRR | latency p50 / p95 |")
    out.append("|---|---|---|---|---|---|---|")
    styles = []
    for name, label in RETRIEVAL_RUNS:
        s = _load(f"retrieval_{name}")
        if not s:
            continue
        s = s["summary"]
        out.append(f"| {label} | {_f(s['hit@1'])} | {_f(s['hit@3'])} | {_f(s['hit@5'])} | "
                   f"{_f(s['recall@5'])} | {_f(s['mrr'])} | "
                   f"{_ms(s['retrieve_ms_p50'])} / {_ms(s['retrieve_ms_p95'])} |")
        styles.append((label, s["by_style"]))
    if styles:
        out.append("\n**MRR by question style**\n")
        keys = list(styles[0][1])
        head = " | ".join(f"{k} (n={styles[0][1][k]['n']})" for k in keys)
        out.append(f"| Config | {head} |")
        out.append("|---|" + "---|" * len(keys))
        for label, bs in styles:
            out.append(f"| {label} | " + " | ".join(_f(bs[k]["mrr"]) for k in keys) + " |")

    out.append("\n## Answers (end to end)\n")
    out.append("| Run | Expected source in LLM context | Refusal acc. (unanswerable) | "
               "False refusals (answerable) | Key-fact "
               "recall | Faithfulness | Citation correct | Numbers verified | Citations valid | "
               "Cited-doc precision |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    present = []
    for name, label in ANSWER_RUNS:
        s = _load(f"answers_{name}")
        if not s:
            continue
        present.append(name)
        s = s["summary"]
        out.append(
            f"| {label} | {_f(s['hit@5'], True)} | {_f(s['refusal_accuracy'], True)} | "
            f"{_f(s['false_refusal_rate'], True)}"
            f" | {_f(s['key_fact_recall'])} | {_f(s['faithfulness'])} | "
            f"{_f(s['citation_correct'])} | {_f(s.get('numbers_verified'), True)} | "
            f"{_f(s['citation_valid'], True)} | "
            f"{_f(s['cited_doc_precision'])} |"
        )
    for name in present:
        s = _load(f"answers_{name}")["summary"]
        out.append(f"\n`{name}`: answers by {s['providers']}; refusals by gate "
                   f"{s['refused_by']['gate']}, by LLM {s['refused_by']['llm']}; "
                   f"self-judged answers {s.get('self_judged', 0)}"
                   + (f"; failed questions {s['errors']}" if s.get("errors") else "") + ".")

    from care_rag.evaluate import judge_agreement

    ja = judge_agreement()
    if ja:
        out.append(f"\n**Judge check:** on {ja['n']} hand-labelled answers the judge agreed with "
                   f"the human label (all claims supported or not) {ja['agreement']:.0%} of "
                   "the time.")
        for d in ja["disagreements"]:
            out.append(f"- disagreement `{d['run']}/{d['id']}`: human "
                       f"{'faithful' if d['human'] else 'unfaithful'}, judge score "
                       f"{d['judge_score']:.2f}")

    bench = _load("latency_bench")
    if bench:
        b = bench["summary"]
        out.append(f"\n## Latency (uncached, {b['n']} questions, "
                   f"`{bench['meta']['config']['name']}`, M2 MacBook Air 8 GB)\n")
        out.append("| Stage | p50 | p95 |")
        out.append("|---|---|---|")
        for st in ("retrieve", "rewrite", "generate", "total"):
            if st in b:
                out.append(f"| {st} | {_ms(b[st]['p50'])} | {_ms(b[st]['p95'])} |")

    gate = _load("gate_calibration")
    if gate:
        g = gate["summary"]
        out.append("\n## Refusal-gate calibration (best cosine similarity in top-5)\n")
        out.append(f"- answerable: min {min(g['answerable_sims']):.3f}, "
                   f"median {sorted(g['answerable_sims'])[len(g['answerable_sims']) // 2]:.3f}")
        out.append(f"- unanswerable: {', '.join(f'{x:.3f}' for x in g['unanswerable_sims'])}")
        out.append(f"- highest threshold with zero false refusals: {g['recommended']}")

    if present:
        default = "hybrid_rerank_small" if "hybrid_rerank_small" in present else present[0]
        rows = sorted(_rows(f"answers_{default}"), key=badness, reverse=True)[:5]
        out.append(f"\n## Worst 5 answers (`{default}`), ranked automatically\n")
        for r in rows:
            out.append(f"**{r['id']}** ({r['style']}, "
                       f"{'answerable' if r['answerable'] else 'unanswerable'}): {r['question']}")
            ans = r["answer"].replace("\n", " ")
            out.append(f"- answer: {ans[:400]}{'...' if len(ans) > 400 else ''}")
            out.append(f"- retrieved: {', '.join(r['retrieved_docs'][:5])}")
            extra = []
            for k in ("hit@5", "key_fact_recall", "faithfulness"):
                if r.get(k) is not None:
                    extra.append(f"{k}={r[k]:.2f}")
            if r.get("unverified_numbers"):
                extra.append(f"numbers not in sources: {r['unverified_numbers']}")
            if r.get("unsupported"):
                extra.append(f"unsupported: {r['unsupported'][:2]}")
            out.append(f"- scores: {'; '.join(extra) or '-'}\n")

    path = RESULTS_DIR / "RESULTS.md"
    RESULTS_DIR.mkdir(exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return str(path)
